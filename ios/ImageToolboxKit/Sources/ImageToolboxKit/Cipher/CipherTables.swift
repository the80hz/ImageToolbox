enum CipherTables {

  /// Decodes a string of hexadecimal digits, ignoring white space, into bytes.
  static func bytes(_ hex: String) -> [UInt8] {
    var result: [UInt8] = []
    result.reserveCapacity(hex.utf8.count / 2)
    var high: UInt8?
    for character in hex.utf8 {
      let digit: UInt8
      switch character {
      case 0x30...0x39: digit = character - 0x30
      case 0x61...0x66: digit = character - 0x61 + 10
      case 0x41...0x46: digit = character - 0x41 + 10
      default: continue
      }
      if let upper = high {
        result.append(upper << 4 | digit)
        high = nil
      } else {
        high = digit
      }
    }
    return result
  }

  /// Decodes big-endian 32-bit words from hexadecimal text.
  static func words(_ hex: String) -> [UInt32] {
    let raw = bytes(hex)
    var result: [UInt32] = []
    result.reserveCapacity(raw.count / 4)
    var index = 0
    while index + 3 < raw.count {
      var word = UInt32(raw[index])
      word = word << 8 | UInt32(raw[index + 1])
      word = word << 8 | UInt32(raw[index + 2])
      word = word << 8 | UInt32(raw[index + 3])
      result.append(word)
      index += 4
    }
    return result
  }

  /// Decodes one nibble per hexadecimal digit.
  static func nibbles(_ hex: String) -> [UInt8] {
    hex.utf8.compactMap { character in
      switch character {
      case 0x30...0x39: character - 0x30
      case 0x61...0x66: character - 0x61 + 10
      case 0x41...0x46: character - 0x41 + 10
      default: nil
      }
    }
  }

