import Foundation
import Testing

@testable import ImageToolboxKit

// Byte layout of the Adobe Swatch Exchange format, checked against the Android ASE coder.

@Suite("Android layout: Adobe Swatch Exchange")
struct PaletteAndroidLayoutTestsASE {

  @Test("ASE writer produces the Android block headers, UTF-16 names and RGB floats")
  func aseWriterLayout() {
    let data = ASEPaletteCoder.encode([
      PaletteColour(name: "Red", red: 255, green: 0, blue: 0),
      PaletteColour(red: 0, green: 0, blue: 255),
    ])
    let expected: [UInt8] = [
      0x41, 0x53, 0x45, 0x46,  // "ASEF"
      0x00, 0x01, 0x00, 0x00,  // version 1.0
      0x00, 0x00, 0x00, 0x02,  // two blocks
      // "Red": block type, block length 0x1C, name length 4, "Red" and its zero unit.
      0x00, 0x01, 0x00, 0x00, 0x00, 0x1C,
      0x00, 0x04, 0x00, 0x52, 0x00, 0x65, 0x00, 0x64, 0x00, 0x00,
      0x52, 0x47, 0x42, 0x20,  // "RGB "
      0x3F, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,  // 1.0, 0.0, 0.0
      0x00, 0x00,  // global colour type
      // Unnamed blue: name length 1 and only the zero unit, block length 0x16.
      0x00, 0x01, 0x00, 0x00, 0x00, 0x16,
      0x00, 0x01, 0x00, 0x00,
      0x52, 0x47, 0x42, 0x20,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3F, 0x80, 0x00, 0x00,  // 0.0, 0.0, 1.0
      0x00, 0x00,
    ]
    #expect(Array(data) == expected)
  }

  @Test("ASE reader accepts Android blocks with a group and a grey colour")
  func aseReaderOnAndroidBytes() throws {
    let file: [UInt8] = [
      0x41, 0x53, 0x45, 0x46, 0x00, 0x01, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x04,  // four blocks
      // Global "Red".
      0x00, 0x01, 0x00, 0x00, 0x00, 0x1C,
      0x00, 0x04, 0x00, 0x52, 0x00, 0x65, 0x00, 0x64, 0x00, 0x00,
      0x52, 0x47, 0x42, 0x20,
      0x3F, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00,
      // Group start with the name "G".
      0xC0, 0x01, 0x00, 0x00, 0x00, 0x06, 0x00, 0x02, 0x00, 0x47, 0x00, 0x00,
      // Grey "Gr" with a value of 0.5, inside the group.
      0x00, 0x01, 0x00, 0x00, 0x00, 0x12,
      0x00, 0x03, 0x00, 0x47, 0x00, 0x72, 0x00, 0x00,
      0x47, 0x72, 0x61, 0x79,  // "Gray"
      0x3F, 0x00, 0x00, 0x00,
      0x00, 0x00,
      // Group end.
      0xC0, 0x02, 0x00, 0x00, 0x00, 0x00,
    ]
    let colours = try ASEPaletteCoder.decode(Data(file))
    #expect(
      colours == [
        PaletteColour(name: "Red", red: 255, green: 0, blue: 0),
        PaletteColour(name: "Gr", red: 128, green: 128, blue: 128),
      ])
  }
}
