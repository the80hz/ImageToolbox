import Foundation
import Testing

@testable import ImageToolboxKit

// Byte layouts of the Adobe Color Book, ColorPaletteCodable and RIFF palette formats, checked
// against the Android coders. The expected bytes are the ones the Android writers produce.

@Suite("Android layout: ACB, DCP and RIFF binary palettes")
struct PaletteAndroidLayoutTestsBinary {

  @Test("ACB writer writes the Pascal title, the RGB book and the hex code of each colour")
  func acbWriterLayout() {
    let data = ACBPaletteCoder.encode([PaletteColour(name: "Ab", red: 1, green: 2, blue: 3)])
    let expected: [UInt8] = [
      0x38, 0x42, 0x43, 0x42,  // "8BCB"
      0x00, 0x01, 0x00, 0x00,  // version 1 and identifier 0
      // Title "Palette": a 32-bit count of units, then the units in big-endian order.
      0x00, 0x00, 0x00, 0x07,
      0x00, 0x50, 0x00, 0x61, 0x00, 0x6C, 0x00, 0x65, 0x00, 0x74, 0x00, 0x74, 0x00, 0x65,
      0x00, 0x00, 0x00, 0x00,  // prefix
      0x00, 0x00, 0x00, 0x00,  // suffix
      0x00, 0x00, 0x00, 0x00,  // description
      0x00, 0x01,  // colour count
      0x00, 0x00,  // page size
      0x00, 0x00,  // page selector offset
      0x00, 0x00,  // RGB colour space
      // Colour "Ab", then its hex code "010203" and the three channels.
      0x00, 0x00, 0x00, 0x02, 0x00, 0x41, 0x00, 0x62,
      0x30, 0x31, 0x30, 0x32, 0x30, 0x33,
      0x01, 0x02, 0x03,
    ]
    #expect(Array(data) == expected)
  }

  @Test("ACB writer names an unnamed colour \"Color\"")
  func acbUnnamedColour() {
    let data = Array(ACBPaletteCoder.encode([PaletteColour(red: 0, green: 0, blue: 0)]))
    let colourStart = data.count - 3 - 6 - (4 + 10)
    #expect(
      Array(data[colourStart..<colourStart + 14])
        == [0x00, 0x00, 0x00, 0x05, 0x00, 0x43, 0x00, 0x6F, 0x00, 0x6C, 0x00, 0x6F, 0x00, 0x72])
  }

  @Test("ACB reader skips a colour with neither a name nor a code, as the Android coder does")
  func acbReaderOnAndroidBytes() throws {
    let file: [UInt8] = [
      0x38, 0x42, 0x43, 0x42, 0x00, 0x01, 0x00, 0x00,
      // Title, prefix, suffix and description, all empty.
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x02,  // two colours
      0x00, 0x00,  // page size
      0x00, 0x00,  // page selector offset
      0x00, 0x00,  // RGB colour space
      0x00, 0x00, 0x00, 0x02, 0x00, 0x41, 0x00, 0x62,
      0x30, 0x31, 0x30, 0x32, 0x30, 0x33,
      0x01, 0x02, 0x03,
      // No name and six spaces as the code: skipped.
      0x00, 0x00, 0x00, 0x00,
      0x20, 0x20, 0x20, 0x20, 0x20, 0x20,
      0x04, 0x05, 0x06,
    ]
    let colours = try ACBPaletteCoder.decode(Data(file))
    #expect(colours == [PaletteColour(name: "Ab", red: 1, green: 2, blue: 3)])
  }

  @Test("DCP writer writes the little-endian header, the global group and float components")
  func dcpWriterLayout() {
    let data = DCPPaletteCoder.encode([PaletteColour(name: "A", red: 255, green: 0, blue: 0)])
    let expected: [UInt8] = [
      0x9C, 0x7D,  // byte order mark 32156
      0x01, 0x00,  // version 1
      0x00, 0x00,  // empty palette name
      0x01, 0x00,  // one group
      0xEA,  // group tag
      // "global" as a pascal string of units.
      0x06, 0x00, 0x67, 0x00, 0x6C, 0x00, 0x6F, 0x00, 0x62, 0x00, 0x61, 0x00, 0x6C, 0x00,
      0x01, 0x00,  // one colour
      0xC0,  // colour tag
      0x01, 0x00, 0x41, 0x00,  // "A"
      0x02,  // RGB
      // 1.0, 0.0 and 0.0 as little-endian floats.
      0x00, 0x00, 0x80, 0x3F, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x80, 0x3F,  // alpha 1.0
      0x01,  // global colour type
    ]
    #expect(Array(data) == expected)
  }

  @Test("DCP reader reads the Android group, colour and alpha layout")
  func dcpReaderOnAndroidBytes() throws {
    let file: [UInt8] = [
      0x9C, 0x7D, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0xEA,
      0x06, 0x00, 0x67, 0x00, 0x6C, 0x00, 0x6F, 0x00, 0x62, 0x00, 0x61, 0x00, 0x6C, 0x00,
      0x01, 0x00, 0xC0, 0x01, 0x00, 0x41, 0x00, 0x02,
      0x00, 0x00, 0x80, 0x3F, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x80, 0x3F, 0x01,
    ]
    let colours = try DCPPaletteCoder.decode(Data(file))
    #expect(colours == [PaletteColour(name: "A", red: 255, green: 0, blue: 0)])
  }

  @Test("RIFF writer writes the chunk sizes and the name chunk of the Android coder")
  func riffWriterLayout() {
    let data = RIFFPaletteCoder.encode([
      PaletteColour(name: "Red", red: 255, green: 0, blue: 0),
      PaletteColour(red: 0, green: 255, blue: 0),
    ])
    let expected: [UInt8] = [
      0x52, 0x49, 0x46, 0x46,  // "RIFF"
      0x24, 0x00, 0x00, 0x00,  // size of the rest of the file, 36
      0x50, 0x41, 0x4C, 0x20,  // "PAL "
      0x64, 0x61, 0x74, 0x61,  // "data"
      0x0C, 0x00, 0x00, 0x00,  // data chunk size, 12
      0x03, 0x00,  // palette version 3
      0x02, 0x00,  // two entries
      0xFF, 0x00, 0x00, 0x00,
      0x00, 0xFF, 0x00, 0x00,
      0x6E, 0x61, 0x6D, 0x65,  // "name"
      0x04, 0x00, 0x00, 0x00,  // "Red\n" has four bytes, so no padding
      0x52, 0x65, 0x64, 0x0A,
    ]
    #expect(Array(data) == expected)
  }

  @Test("RIFF writer pads an odd length name chunk with one zero byte")
  func riffOddNamePadding() {
    let data = RIFFPaletteCoder.encode([PaletteColour(name: "A", red: 255, green: 0, blue: 0)])
    let expected: [UInt8] = [
      0x52, 0x49, 0x46, 0x46, 0x1E, 0x00, 0x00, 0x00, 0x50, 0x41, 0x4C, 0x20,
      0x64, 0x61, 0x74, 0x61, 0x08, 0x00, 0x00, 0x00, 0x03, 0x00, 0x01, 0x00,
      0xFF, 0x00, 0x00, 0x00,
      0x6E, 0x61, 0x6D, 0x65, 0x01, 0x00, 0x00, 0x00, 0x41, 0x00,
    ]
    #expect(Array(data) == expected)
  }

  @Test("RIFF reader reads Android entries and the name chunk")
  func riffReaderOnAndroidBytes() throws {
    let file: [UInt8] = [
      0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x50, 0x41, 0x4C, 0x20,
      0x64, 0x61, 0x74, 0x61, 0x0C, 0x00, 0x00, 0x00, 0x03, 0x00, 0x02, 0x00,
      0xFF, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x00, 0x00,
      0x6E, 0x61, 0x6D, 0x65, 0x04, 0x00, 0x00, 0x00, 0x52, 0x65, 0x64, 0x0A,
    ]
    let colours = try RIFFPaletteCoder.decode(Data(file))
    #expect(
      colours == [
        PaletteColour(name: "Red", red: 255, green: 0, blue: 0),
        PaletteColour(red: 0, green: 255, blue: 0),
      ])
  }
}
